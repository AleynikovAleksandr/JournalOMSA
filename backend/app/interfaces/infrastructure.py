"""Протоколы инфраструктурных компонентов."""

from __future__ import annotations

from collections.abc import Iterable
from datetime import datetime, timedelta
from typing import Protocol
from uuid import UUID

from core.interprocess.locks import LockOwner, LockResult
from core.security.login_limits import LockableAccount
from core.security.tokens import AccessTokenClaims


class PasswordHasher(Protocol):
    def hash(self, password: str) -> str: ...
    def verify(self, password_hash: str, password: str) -> bool: ...
    def needs_rehash(self, password_hash: str) -> bool: ...
    def burn(self, password: str) -> None: ...


class TokenCodec(Protocol):
    @property
    def ttl(self) -> timedelta: ...
    def issue(self, subject: UUID, *, audience: str, now: datetime) -> tuple[str, datetime]: ...
    def decode(self, token: str, *, audience: str, now: datetime) -> AccessTokenClaims: ...


class LoginAttemptLimiter(Protocol):
    def is_blocked(self, ip: str | None) -> bool: ...
    def register_failure(self, ip: str | None) -> None: ...


class UnknownLoginAttempts(Protocol):
    """Счётчик попыток несуществующего логина: None — счётчик недоступен."""

    def register_failure(self, login: str, now: datetime) -> LockableAccount | None: ...


class HandoffTickets(Protocol):
    def issue(self, user_uuid: UUID, session_id: UUID) -> str | None: ...
    def redeem(self, ticket: str) -> tuple[UUID, UUID] | None: ...


class EditLockManager(Protocol):
    @property
    def ttl_seconds(self) -> int: ...
    def acquire(self, resource: str, owner: LockOwner) -> LockResult: ...
    def release(self, resource: str, owner: LockOwner) -> None: ...
    def holder(self, resource: str) -> LockOwner | None: ...


class AccessControl(Protocol):
    def allows(self, subjects: Iterable[str], obj: str, act: str) -> bool: ...
