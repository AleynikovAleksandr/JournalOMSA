"""Протоколы репозиториев и единицы работы."""

from __future__ import annotations

from collections.abc import Callable, Iterable, Sequence
from datetime import date, datetime
from typing import Protocol
from uuid import UUID

from app.models.auth import RefreshToken
from app.models.journal import CheckGroup, JournalRecord
from app.models.notification import Notification, NotificationKind, NotificationSubscription, PushSubscription
from app.models.organization import Organization
from app.models.references import Category, Option, Solution, TypeCheck
from app.models.user import User, UserGroup
from app.repositories.notifications.notifications import PlannedNotification
from app.schemas.commands import JournalFilter


class UserRepo(Protocol):
    def get(self, user_id: int) -> User | None: ...
    def get_by_uuid(self, user_uuid: UUID) -> User | None: ...
    def get_by_login(self, login: str) -> User | None: ...
    def login_taken(self, login: str, *, exclude_id: int | None = None) -> bool: ...
    def list(
        self, *, search: str | None = None, group_id: int | None = None, include_fired: bool = True
    ) -> list[User]: ...
    def executors(self) -> list[User]: ...
    def is_referenced_in_journal(self, user_id: int) -> bool: ...
    def count_in_group(self, group_id: int) -> int: ...
    def add(self, user: User) -> None: ...
    def delete(self, user: User) -> None: ...


class UserGroupRepo(Protocol):
    def list(self) -> list[UserGroup]: ...
    def get(self, group_id: int) -> UserGroup | None: ...
    def name_taken(self, name: str, *, exclude_id: int | None = None) -> bool: ...
    def member_counts(self) -> tuple[dict[int, int], int]: ...
    def add(self, group: UserGroup) -> None: ...
    def delete(self, group: UserGroup) -> None: ...


class ReferenceRepo(Protocol):
    def categories(self) -> list[Category]: ...
    def type_checks(self) -> list[TypeCheck]: ...
    def solutions(self) -> list[Solution]: ...
    def category(self, category_id: int) -> Category | None: ...
    def type_check(self, type_check_id: int) -> TypeCheck | None: ...
    def solution(self, solution_id: int) -> Solution | None: ...
    def final_solution(self) -> Solution | None: ...
    def default_solution(self) -> Solution | None: ...
    def add_category(self, item: Category) -> None: ...
    def add_type_check(self, item: TypeCheck) -> None: ...
    def add_solution(self, item: Solution) -> None: ...
    def options(self) -> list[Option]: ...
    def add_option(self, item: Option) -> None: ...


class OrganizationRepo(Protocol):
    def list(self, *, search: str | None = None) -> list[Organization]: ...
    def get(self, organization_id: int) -> Organization | None: ...
    def is_used(self, organization_id: int) -> bool: ...
    def add(self, organization: Organization) -> None: ...
    def delete(self, organization: Organization) -> None: ...


class CheckGroupRepo(Protocol):
    def list(self, *, date_from: date | None = None, date_to: date | None = None) -> list[tuple[CheckGroup, int]]: ...
    def get(self, group_id: int) -> CheckGroup | None: ...
    def find(self, check_date: date, check_time: str, type_check_id: int) -> CheckGroup | None: ...
    def add(self, group: CheckGroup) -> None: ...
    def delete(self, group: CheckGroup) -> None: ...


class JournalRepo(Protocol):
    def list(self, flt: JournalFilter) -> list[JournalRecord]: ...
    def get(self, record_id: int) -> JournalRecord | None: ...
    def in_group(self, group_id: int) -> list[JournalRecord]: ...
    def active_until(self, last_date: date) -> list[JournalRecord]: ...
    def next_number(self, group_id: int) -> int: ...
    def add(self, record: JournalRecord) -> None: ...
    def delete(self, record: JournalRecord) -> None: ...


class RefreshTokenRepo(Protocol):
    def get(self, token_id: UUID) -> RefreshToken | None: ...
    def add(self, token: RefreshToken) -> None: ...
    def delete(self, token: RefreshToken) -> None: ...
    def delete_for_user(self, user_uuid: UUID) -> int: ...
    def delete_session(self, session_id: UUID) -> int: ...
    def session_active(self, session_id: UUID, *, portal: str, now: datetime) -> bool: ...
    def delete_expired(self, now: datetime) -> int: ...


class NotificationRepo(Protocol):
    def insert_ignore(self, planned: Sequence[PlannedNotification], *, created_at: datetime) -> int: ...
    def pending(self, user_uuid: UUID, now: datetime) -> list[Notification]: ...
    def history(self, user_uuid: UUID, *, limit: int = 200) -> list[Notification]: ...
    def get(self, notification_id: int) -> Notification | None: ...
    def delete_unshown(
        self,
        journal_id: int,
        *,
        user_uuid: UUID | None = None,
        kinds: Iterable[NotificationKind] | None = None,
    ) -> int: ...


class SubscriptionRepo(Protocol):
    def find(self, user_uuid: UUID, user_agent: str) -> NotificationSubscription | None: ...
    def add(self, subscription: NotificationSubscription) -> None: ...


class PushRepo(Protocol):
    def find_endpoint(self, endpoint: str) -> PushSubscription | None: ...
    def add(self, subscription: PushSubscription) -> None: ...
    def delete_session(self, session_id: UUID) -> None: ...
    def delete_for_user(self, user_uuid: UUID) -> None: ...


class UnitOfWork(Protocol):
    users: UserRepo
    user_groups: UserGroupRepo
    references: ReferenceRepo
    organizations: OrganizationRepo
    groups: CheckGroupRepo
    journal: JournalRepo
    refresh_tokens: RefreshTokenRepo
    notifications: NotificationRepo
    subscriptions: SubscriptionRepo
    push: PushRepo

    def after_commit(self, callback: Callable[[], None]) -> None: ...
    def flush(self) -> None: ...
    def commit(self) -> None: ...
    def rollback(self) -> None: ...
